export const GLYPH_W = 5;
export const GLYPH_H = 7;
const SPACING = 1;

/** Width in pixels that `text` will occupy. */
export function measure(text: string): number {
  if (!text) return 0;
  return text.length * (GLYPH_W + SPACING) - SPACING;
}

/**
 * Draws `text` as hard pixels. Coordinates are top-left unless an alignment is
 * given; unknown characters are skipped rather than drawn as tofu.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  align: "left" | "center" | "right" = "left"
) {
  const upper = text.toUpperCase();
  const w = measure(upper);
  let cx = Math.round(x);
  if (align === "center") cx -= Math.floor(w / 2);
  else if (align === "right") cx -= w;
  const cy = Math.round(y);

  ctx.fillStyle = color;
  for (let i = 0; i < upper.length; i++) {
    const rows = GLYPHS[upper[i]];
    const gx = cx + i * (GLYPH_W + SPACING);
    if (!rows) continue;
    for (let r = 0; r < GLYPH_H; r++) {
      const row = rows[r];
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === "#") ctx.fillRect(gx + c, cy + r, 1, 1);
      }
    }
  }
}

/** Text with a one-pixel drop shadow, so it stays legible over any terrain. */
export function drawTextShadowed(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  align: "left" | "center" | "right" = "left",
  shadow = "#05070c"
) {
  drawText(ctx, text, x + 1, y + 1, shadow, align);
  drawText(ctx, text, x, y, color, align);
}
